import torch
import torch.nn as nn
import torch.nn.functional as F

# 固定随机种子并设置打印精度
torch.manual_seed(42)
torch.set_printoptions(precision=3, sci_mode=False)

# 1. 现实世界词表 (Vocabulary)
VOCAB = {0: "[PAD]", 1: "我", 2: "爱", 3: "吃", 4: "面", 5: "米"}
VOCAB_SIZE = len(VOCAB)
D_MODEL = 4  # 隐藏层维度设为 4, 便于查看矩阵具体数值


class MiniLLM(nn.Module):
    """
    具备完整 LLM 结构的单层 Decoder-only 语言模型
    结构: Embedding -> Attention(Q, K, V) -> FFN -> LM Head -> Softmax
    """

    def __init__(self, vocab_size=VOCAB_SIZE, d_model=D_MODEL):
        super().__init__()
        self.d_model = d_model

        # 1. 词嵌入层
        self.token_embedding = nn.Embedding(vocab_size, d_model)

        # 2. 注意力投影层
        self.w_q = nn.Linear(d_model, d_model, bias=False)
        self.w_k = nn.Linear(d_model, d_model, bias=False)
        self.w_v = nn.Linear(d_model, d_model, bias=False)

        self.w_out = nn.Linear(d_model, d_model, bias=False)

        # 3. 前馈全连接网络 (FFN / MLP)
        self.ffn = nn.Sequential(
            nn.Linear(d_model, d_model * 2), nn.ReLU(), nn.Linear(d_model * 2, d_model)
        )

        # 4. 语言模型分类头 (LM Head)
        self.lm_head = nn.Linear(d_model, vocab_size, bias=True)

    def forward(self, input_ids):
        seq_len = input_ids.shape[1]
        print(f"输入 input_ids 的形状: {input_ids.shape}")
        print(f"输入 input_ids: \n{input_ids}")

        # --- 步骤 1: Embedding 映射 ---
        x = self.token_embedding(input_ids)
        print(f"\n[Layer 1: Embedding 输出]")
        print(f"X 的形状: {x.shape}")
        print(f"X: \n{x}")

        # --- 步骤 2: 计算 Q, K, V ---
        Q = self.w_q(x)
        K = self.w_k(x)
        V = self.w_v(x)

        print(f"\n[Layer 2: 投影计算 Q, K, V]")
        print(f"Q 的形状: {Q.shape}")
        print(f"Q: \n{Q}")
        print(f"K 的形状: {K.shape}")
        print(f"K: \n{K}")
        print(f"V 的形状: {V.shape}")
        print(f"V: \n{V}")

        # --- 步骤 3: 因果注意力计算 (Scaled Dot-Product + Mask) ---
        scores = torch.matmul(Q, K.transpose(-2, -1)) / (self.d_model**0.5)
        mask = torch.triu(torch.full((seq_len, seq_len), float("-inf")), diagonal=1)
        masked_scores = scores + mask
        attn_weights = F.softmax(masked_scores, dim=-1)

        print(f"\n[Layer 3: 注意力权重矩阵 (Softmax)]")
        print(f"attn_weights 的形状: {attn_weights.shape}")
        print(f"attn_weights: \n{attn_weights}")

        # 注意力加权求和并经过投影
        attn_out = self.w_out(torch.matmul(attn_weights, V))

        # --- 步骤 4: 前馈神经网络 (FFN) ---
        ffn_out = self.ffn(attn_out)
        print(f"\n[Layer 4: 前馈网络 FFN 输出]")
        print(f"ffn_out 的形状: {ffn_out.shape}")
        print(f"ffn_out: \n{ffn_out}")

        # --- 步骤 5: LM Head 输出词表概率 ---
        logits = self.lm_head(ffn_out)
        probs = F.softmax(logits, dim=-1)
        print(f"\n[Layer 5: 最终预测概率分布 (Softmax)]")
        print(f"probs 的形状: {probs.shape} -> [batch, seq_len, vocab_size]")
        print(f"probs: \n{probs}")

        return Q, K, V, probs


def main():
    model = MiniLLM()
    model.eval()

    # 为了稳定演示, 微调 LM Head 偏置, 让模型预测当前序列下一个词时必定选择 "面" (ID: 4)
    with torch.no_grad():
        model.lm_head.bias[4] += 5.0

    print("=" * 75)
    print("[第一轮前向传播]: 输入 Prompt 提示词 ['我', '爱', '吃'] (seq_len = 3)")
    print("=" * 75)

    # 输入: "我"(1), "爱"(2), "吃"(3)
    input_ids_1 = torch.tensor([[1, 2, 3]])
    with torch.no_grad():
        Q1, K1, V1, probs1 = model(input_ids_1)

    # 查看最后一个位置 (第 2 个位置, 即 "吃") 预测出的下一个词
    next_token_probs = probs1[0, -1, :]  # 提取最后一个位置的词表概率
    next_token_id = torch.argmax(next_token_probs).item()
    next_token_word = VOCAB[next_token_id]

    print("\n" + "-" * 60)
    print(f"第 1 轮最后一个位置 (词: '吃') 对下一个字的概率预测:")
    for token_id, token_name in VOCAB.items():
        print(
            f"  预测为 '{token_name}' (ID: {token_id}) 的概率: {next_token_probs[token_id].item():.4f}"
        )
    print(f"---> 概率最大的是 ID={next_token_id}, 即真实字:['{next_token_word}']! ")
    print("-" * 60)

    print("\n" + "=" * 75)
    print(
        "[第二轮前向传播]: 把预测的 '面' 追加到末尾, 全量重算 ['我', '爱', '吃', '面'] (seq_len = 4)"
    )
    print("=" * 75)

    # 输入变为: "我"(1), "爱"(2), "吃"(3), "面"(4)
    input_ids_2 = torch.tensor([[1, 2, 3, 4]])
    with torch.no_grad():
        Q2, K2, V2, probs2 = model(input_ids_2)

    # =========================================================================
    # 核心分析: 对比两次运算中的 Q、K、V
    # =========================================================================
    print("\n" + "=" * 75)
    print("[深度对比与为什么 Q 不能缓存的硬核解释]")
    print("=" * 75)

    print("\n1. [K 矩阵对比]:")
    print("第 1 轮前 3 个 Token 的 K:\n", K1[0])
    print("第 2 轮前 3 个 Token 的 K:\n", K2[0, :3])
    print(f"--> K 是否完全一模一样? {torch.allclose(K1[0], K2[0, :3])}")

    print("\n2. [V 矩阵对比]:")
    print("第 1 轮前 3 个 Token 的 V:\n", V1[0])
    print("第 2 轮前 3 个 Token 的 V:\n", V2[0, :3])
    print(f"--> V 是否完全一模一样? {torch.allclose(V1[0], V2[0, :3])}")

    print("\n3. [Q 矩阵对比]:")
    print("第 1 轮前 3 个 Token 的 Q:\n", Q1[0])
    print("第 2 轮前 3 个 Token 的 Q:\n", Q2[0, :3])
    print(f"--> Q 是否完全一模一样? {torch.allclose(Q1[0], Q2[0, :3])}")

    print("\n" + "*" * 75)
    print("[解答关键疑问: 为什么 Q 值明明数值一样, 却根本不需要也不应该缓存?]")
    print("*" * 75)
    print("""
我们在第 2 轮中, 目标是生成第 5 个字(预测 '面' 后面的字).
为了生成第 5 个字, 我们需要的是: 整个序列最后一行(即 '面' 所在位置)的输出!

回顾自注意力的计算公式:
第 3 行('面' 这一行)的隐状态 =
   Softmax( Q['面'] × K['我', '爱', '吃', '面']^T ) × V['我', '爱', '吃', '面']

请看这三者的职责分工:

  ● Q 代表[发起查询的主体]:
    现在是谁在询问下文? 只有最新生成的['面']在询问!
    它只用它自己的 Q['面'](单单一个向量)去查.
    至于过去的 Q['我']、Q['爱']、Q['吃'], 是过去用来预测别的字的,
    在这一步它们[彻底失去任何利用价值]! 它们不会参与 '面' 的预测计算!

  ● K 代表[被查询的词索引]:
    '面' 在查询时, 必须知道过去所有字是谁, 所以需要整个历史的 K['我', '爱', '吃', '面'].
    因此历史的 K 必须存下来, 随时供后续任意新字来查找.

  ● V 代表[被提取的内容信息]:
    '面' 算完注意力权重后, 要从所有历史字中抽取信息, 所以需要历史所有的 V['我', '爱', '吃', '面'].
    因此历史的 V 也必须存下来.

[结论]:
并不是因为 Q 的值改变了才不缓存, 而是因为:
过去的所有 Q 在未来的生成步骤中[永远不会再被用到](使用次数为 0)!
缓存它们纯属浪费显存.

在真正的 KV Cache 优化工程中:
第 2 轮我们根本不会输入 ['我', '爱', '吃', '面'],
而是仅仅把['面']这一个字送进模型:
  -> 模型只计算 Q['面'], K['面'], V['面'] (形状都是 [1, 1, 4])
  -> 历史的 Q['我', '爱', '吃'] 压根连算都不去算!
  -> 取出缓存的 K, V 拼上新的 K['面'], V['面'], 完成解码.
""")
    print("=" * 75)


if __name__ == "__main__":
    main()

