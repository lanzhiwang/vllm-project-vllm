import torch
import torch.nn as nn
import torch.nn.functional as F

# 1. 固定随机数种子, 保证每次运行看到的数值完全一样
torch.manual_seed(42)
torch.set_printoptions(precision=2, sci_mode=False)


class TransparentAttention(nn.Module):
    """
    一个完全透明的单层注意力模块, 打印每一步的真实数值
    """

    def __init__(self, d_model=3):
        super().__init__()
        self.d_model = d_model
        # 定义 Q, K, V 投影矩阵(相当于给每个词变换形态)
        self.w_q = nn.Linear(d_model, d_model, bias=False)
        self.w_k = nn.Linear(d_model, d_model, bias=False)
        self.w_v = nn.Linear(d_model, d_model, bias=False)
        self.w_out = nn.Linear(d_model, d_model, bias=False)

    def forward(self, x, token_names):
        seq_len = x.shape[1]
        print(f"\n{'=' * 20} 前向传播开始 (序列长度 = {seq_len}) {'=' * 20}")
        print(f"输入 X 的形状: {list(x.shape)} -> [batch_size, seq_len, d_model]")
        print(f"输入 X: {x}")
        print()

        # 1. 投影计算 Q, K, V
        Q = self.w_q(x)
        K = self.w_k(x)
        V = self.w_v(x)

        print("\n--- 关键点: 投影计算 Q、K、V ---")
        print(f"Q 的形状: {list(Q.shape)}")
        print(f"Q: {Q}")
        print(f"K 的形状: {list(K.shape)}")
        print(f"K: {K}")
        print(f"V 的形状: {list(V.shape)}")
        print(f"V: {V}")

        # 2. 计算注意力分数
        scores = torch.matmul(Q, K.transpose(-2, -1)) / (self.d_model**0.5)

        # 3. 因果掩码(下三角矩阵, 前面的字不能看后面的字)
        mask = torch.triu(torch.full((seq_len, seq_len), float("-inf")), diagonal=1)
        masked_scores = scores + mask
        attn_weights = F.softmax(masked_scores, dim=-1)

        print("\n--- 注意力权重矩阵 (Softmax 后) ---")
        print(f"权重矩阵形状: {list(attn_weights.shape)}")
        for i, name in enumerate(token_names):
            weights = [round(w, 2) for w in attn_weights[0, i].tolist()]
            print(f"  Token {i} [{name}] 对全句每个词的关注度: {weights}")

        # 4. 加权求和得到输出
        context = torch.matmul(attn_weights, V)
        out = self.w_out(context)
        print(f"\n输出 Out 的形状: {list(out.shape)}")
        print(f"输出 Out: {out}")
        print(f"{'=' * 56}\n")

        return Q, K, V, out


def main():
    d_model = 3  # 每个词用 3 个数字表示
    model = TransparentAttention(d_model=d_model)
    model.eval()

    # 模拟 4 个词的初始语义向量 (每个词 3 个数字)
    token_embeddings = {
        "我": torch.tensor([[0.50, 1.20, -0.30]]),
        "爱": torch.tensor([[-0.20, 0.80, 1.50]]),
        "吃": torch.tensor([[1.10, -0.60, 0.40]]),
        "面": torch.tensor([[0.30, 0.70, -0.90]]),
    }

    # =========================================================================
    # 第一阶段: Prompt 阶段, 输入 3 个字 ["我", "爱", "吃"]
    # =========================================================================
    prompt_tokens = ["我", "爱", "吃"]
    x1 = torch.cat([token_embeddings[w] for w in prompt_tokens], dim=0).unsqueeze(0)
    # x1 形状为 [1, 3, 3]

    print("\n" + "#" * 70)
    print("[第一阶段]: 输入 Prompt: '我 爱 吃' (seq_len = 3)")
    print("#" * 70)
    with torch.no_grad():
        Q1, K1, V1, _ = model(x1, prompt_tokens)

    # =========================================================================
    # 第二阶段: 生成了一个新字 "面", 此时变成 4 个字 ["我", "爱", "吃", "面"]
    # 模拟传统做法: 不加任何缓存, 直接将 4 个字完整重新喂给模型
    # =========================================================================
    full_tokens = ["我", "爱", "吃", "面"]
    x2 = torch.cat([token_embeddings[w] for w in full_tokens], dim=0).unsqueeze(0)
    # x2 形状为 [1, 4, 3]

    print("\n" + "#" * 70)
    print(
        "[第二阶段]: 吐出新字 '面', 无 Cache 模式下全量重新计算: '我 爱 吃 面' (seq_len = 4)"
    )
    print("#" * 70)
    with torch.no_grad():
        Q2, K2, V2, _ = model(x2, full_tokens)

    # =========================================================================
    # 第三阶段: 对比两次计算的 Q、K、V 数值
    # =========================================================================
    print("\n" + "#" * 70)
    print("[灵魂对比]: 两次运行中, K (Key) 和 V (Value) 的具体数值对比")
    print("#" * 70)

    print("\n[K 矩阵对比]:")
    for i in range(3):
        k1_row = [round(x, 4) for x in K1[0, i].tolist()]
        k2_row = [round(x, 4) for x in K2[0, i].tolist()]
        is_same = k1_row == k2_row
        print(f"Token {i} [{prompt_tokens[i]}]:")
        print(f"   第一次算出的 K: {k1_row}")
        print(
            f"   第二次算出的 K: {k2_row}   <--- 是否完全一致? [{is_same}] (完全被重复计算!)"
        )

    print(f"Token 3 [面] (新生成的字):")
    print(f"   第一次算出的 K: [不存在]")
    print(
        f"   第二次算出的 K: {[round(x, 4) for x in K2[0, 3].tolist()]}   <--- 只有这个是全新的!"
    )

    print("\n[V 矩阵对比]:")
    for i in range(3):
        v1_row = [round(x, 4) for x in V1[0, i].tolist()]
        v2_row = [round(x, 4) for x in V2[0, i].tolist()]
        is_same = v1_row == v2_row
        print(f"Token {i} [{prompt_tokens[i]}]:")
        print(f"   第一次算出的 V: {v1_row}")
        print(
            f"   第二次算出的 V: {v2_row}   <--- 是否完全一致? [{is_same}] (完全被重复计算!)"
        )

    print("\n" + "=" * 70)
    print("[给普通程序员看的极简总结]")
    print("=" * 70)
    print(
        "1. 你可以看到, 第二次计算时, '我'、'爱'、'吃' 对应的 K 和 V 向量, 与第一次算出来的完全一模一样, 小数点后没有一丝偏差!"
    )
    print("2. 在生成新词 '面' 时, 模型只需要知道: ")
    print("   - '面' 自己的 Q 向量(去查询别人)")
    print("   - '我'、'爱'、'吃'、'面' 的 K 向量(用来计算匹配度)")
    print("   - '我'、'爱'、'吃'、'面' 的 V 向量(用来提取内容)")
    print("3. [白费力气的地方]: ")
    print("   第二次运行时, GPU 耗费算力重新把 '我'、'爱'、'吃' 的 K 和 V 算了一遍!")
    print("4. [KV Cache 的解决方案]: ")
    print("   第一次算完把 '我'、'爱'、'吃' 的 K、V 存进显存字典 (Cache);")
    print(
        "   第二次直接把新字 '面' 的向量送入模型, 只算 '面' 的 K、V, 然后和缓存拼起来!"
    )
    print("   这样 GPU 的计算量就从 4 个词变成只算 1 个词, 速度直接起飞!")
    print("=" * 70)


if __name__ == "__main__":
    main()

